#!/usr/bin/env python3
"""Write the 44.1 kHz <-> 96 kHz polyphase resampler coefficients.

Warps' DSP runs at its codec rate, 96 kHz, in blocks of 60 frames; the Move
runs at 44.1 kHz. 96000/44100 = 320/147, so each direction is one fixed
polyphase FIR with an integer phase accumulator: no drift, no interpolation
between phases. Both prototypes live at the same rate, 320 * 44100 =
147 * 96000 = 14.112 MHz (one "tick").

The round trip is designed to be an EXACT number of 44.1 kHz samples, so the
dry signal for MIX can be delayed by that integer and lines up with the wet
one sample for sample (no comb filtering anywhere in the MIX range):

    up   : y96[n]  = x44( (147 n - C_UP) / 320 )
    Warps: w96[j]  = f(y96[j - PRIME])          (PRIME frames of block FIFO)
    down : z44[m]  = w96( (320 m - C_DOWN) / 147 )
    =>     z44[m]  = x44( m - (C_UP + C_DOWN + 147 PRIME) / 320 )

C_UP and C_DOWN are the prototypes' centres (in ticks) and are chosen so the
numerator is a multiple of 320; the result is ROUND_TRIP samples.

Kaiser-windowed sincs. Up: pass to 19.5 kHz, stop at 22.05 kHz (the images of
the 44.1 kHz input), ~88 dB. Down: pass to 19.5 kHz, stop from 24.6 kHz, so
whatever aliases lands above 19.5 kHz, ~93 dB. Each phase is normalised to
unity DC gain. Pure Python: no numpy needed to build.

Copyright (c) 2026 Hiro Ikezawa. MIT License (see LICENSE).
"""
import math
import sys

HOST = 44100
WARPS = 96000
L_UP, M_UP = 320, 147      # 44.1k -> 96k
L_DN, M_DN = 147, 320      # 96k -> 44.1k
K_UP = 96                  # taps per phase (at 44.1 kHz)
K_DN = 112                 # taps per phase (at 96 kHz)
PRIME = 64                 # frames of 96 kHz output primed ahead (>= block 60 + margin)
C_DN = 8231                # centre of the down prototype: (K_DN*L_DN - 1) // 2 - 0
TICK = L_UP * HOST


def choose_c_up():
    # Largest centre inside the up table with (C_UP + C_DN + 147 PRIME) % 320 == 0.
    c = (K_UP * L_UP - 1) // 2
    while (c + C_DN + 147 * PRIME) % 320:
        c -= 1
    return c


C_UP = choose_c_up()
ROUND_TRIP = (C_UP + C_DN + 147 * PRIME) // 320


def bessel_i0(x):
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2.0 * k)) ** 2
        s += term
        k += 1
    return s


def design(L, K, centre, f_pass, f_stop, atten):
    """Prototype of K*L taps, symmetric about `centre`, zero elsewhere."""
    n = K * L
    half = min(centre, n - 1 - centre)
    fc = 0.5 * (f_pass + f_stop) / TICK
    beta = 0.1102 * (atten - 8.7)
    i0b = bessel_i0(beta)
    h = [0.0] * n
    for i in range(centre - half, centre + half + 1):
        t = i - centre
        sinc = 2.0 * fc if t == 0 else math.sin(2.0 * math.pi * fc * t) / (math.pi * t)
        w = bessel_i0(beta * math.sqrt(max(0.0, 1.0 - (t / half) ** 2))) / i0b
        h[i] = sinc * w
    # Phase p holds h[p + k*L], k = 0..K-1, applied to x[i - k]. Stored
    # REVERSED (k = K-1 first) so the dot product walks the history forwards.
    table = []
    for p in range(L):
        phase = [h[p + k * L] for k in range(K)]
        g = sum(phase)
        table.extend(v / g for v in reversed(phase))
    return table


def emit(out, name, L, M, K, table):
    out.append(f"static const int {name}_L = {L};")
    out.append(f"static const int {name}_M = {M};")
    out.append(f"static const int {name}_K = {K};")
    out.append(f"static const float {name}_coef[{L * K}] = {{")
    for i in range(0, len(table), 6):
        out.append("  " + ", ".join(f"{v:.9e}f" for v in table[i:i + 6]) + ",")
    out.append("};")


def main(path):
    assert C_DN <= (K_DN * L_DN - 1) // 2
    out = ["/* Generated by scripts/gen_tables.py - do not edit. */",
           "#ifndef OWARPS_SRC_TABLES_H_", "#define OWARPS_SRC_TABLES_H_", "",
           f"/* centres: up {C_UP} ticks, down {C_DN} ticks; {PRIME} primed frames */",
           f"static const int kSrcPrimeFrames = {PRIME};",
           f"static const int kRoundTripSamples = {ROUND_TRIP};", ""]
    emit(out, "src_up", L_UP, M_UP, K_UP, design(L_UP, K_UP, C_UP, 19500.0, 22050.0, 88.0))
    emit(out, "src_down", L_DN, M_DN, K_DN, design(L_DN, K_DN, C_DN, 19500.0, 24600.0, 93.0))
    out += ["", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
