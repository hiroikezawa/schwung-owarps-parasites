#!/usr/bin/env python3
"""Generate everything that describes the parameters from scripts/param_spec.py.

    scripts/metadata.py OUTDIR            write OUTDIR/owarps_params.h and
                                          OUTDIR/owarps_metadata.h, and FAIL if
                                          module.json's chain_params differ
    scripts/metadata.py --write-module-json
                                          rewrite module.json's chain_params

The runtime callbacks never read files, so chain_params, the ui_hierarchy and
the version are compiled into the DSP.

Copyright (c) 2026 Hiro Ikezawa. MIT License (see LICENSE).
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "scripts"))
import param_spec as spec  # noqa: E402

params = spec.all_params()
module_path = root / "module.json"
meta = json.loads(module_path.read_text())

if sys.argv[1:] == ["--write-module-json"]:
    meta["capabilities"]["chain_params"] = params
    module_path.write_text(json.dumps(meta, indent=2) + "\n")
    print("module.json chain_params rewritten:", len(params), "parameters")
    sys.exit(0)

assert meta["capabilities"]["chain_params"] == params, \
    "module.json chain_params differ from scripts/param_spec.py (run metadata.py --write-module-json)"
assert meta["dsp"] == meta["id"] + ".so", "the chain host loads audio_fx/<id>/<id>.so"
keys = [p["key"] for p in params]
assert len(set(keys)) == len(keys), "duplicate keys"
hier = spec.hierarchy()
for lvl in hier["levels"].values():
    for e in lvl["params"]:
        k = e if isinstance(e, str) else e.get("key")
        if k:
            assert k in keys, k
        if isinstance(e, dict) and "visible_if" in e:
            assert e["visible_if"]["param"] in keys

version = meta["version"]
major, minor, patch = (int(x) for x in version.split("."))


def c_string(text):
    return json.dumps(text, ensure_ascii=True)


def ident(key):
    return "P_" + key.upper()


out = pathlib.Path(sys.argv[1])
lines = ["/* Generated by scripts/metadata.py from scripts/param_spec.py - do not edit. */",
         "#ifndef OWARPS_PARAMS_H_", "#define OWARPS_PARAMS_H_", "",
         "namespace owarps {", "", "enum ParamIndex {"]
lines += [f"  {ident(k)}," for k in keys]
lines += ["  P_COUNT", "};", ""]
lines += ["enum ParamType { TYPE_FLOAT, TYPE_INT, TYPE_ENUM };", "",
          "struct ParamDef {", "  const char* key;", "  ParamType type;", "  float min, max, def;",
          "  int n_options;", "  const char* const* options;", "};", ""]
for p in params:
    if p["type"] == "enum":
        opts = ", ".join(c_string(o) for o in p["options"])
        lines.append(f"static const char* const kOpt_{p['key']}[] = {{{opts}}};")
lines += ["", "static const ParamDef kParams[P_COUNT] = {"]
for p in params:
    if p["type"] == "enum":
        n = len(p["options"])
        lines.append(f'  {{"{p["key"]}", TYPE_ENUM, 0.0f, {n - 1}.0f, '
                     f'{p["options"].index(p["default"])}.0f, {n}, kOpt_{p["key"]}}},')
    else:
        t = "TYPE_INT" if p["type"] == "int" else "TYPE_FLOAT"
        lines.append(f'  {{"{p["key"]}", {t}, {float(p["min"])!r}f, {float(p["max"])!r}f, '
                     f'{float(p["default"])!r}f, 0, 0}},')
lines += ["};", ""]
# Which parameter stands in for which Warps control, per feature mode (the
# firmware's FeatureMode order). -1: the mode has no such control.
lines += ["enum WarpsControl { CTL_ALGO, CTL_PARAM, CTL_LEVEL1, CTL_LEVEL2, CTL_BUTTON, CTL_PITCH,",
          "                    CTL_COUNT };", "",
          f"static const int kNumModes = {len(spec.MODES)};",
          "static const int kModeControls[kNumModes][CTL_COUNT] = {"]
for name, prefix, _ in spec.MODES:
    roles = {r: p["key"] for p, r in spec.PER_MODE[prefix]}
    row = [ident(roles[r]) if r in roles else "-1"
           for r in ("algo", "param", "level1", "level2", "button", "pitch")]
    lines.append(f"  {{{', '.join(row)}}},  // {name}")
lines += ["};", "", "}  // namespace owarps", "", "#endif", ""]
(out / "owarps_params.h").write_text("\n".join(lines))

(out / "owarps_metadata.h").write_text("\n".join([
    "/* Generated by scripts/metadata.py - do not edit. */",
    "static const char kChainParams[] = " + c_string(json.dumps(params, separators=(",", ":"))) + ";",
    "static const char kHierarchy[] = " + c_string(json.dumps(hier, separators=(",", ":"))) + ";",
    f'static const char kVersion[] = "{version}";',
    f"static const int kBuild = {major * 10000 + minor * 100 + patch};",
]) + "\n")
